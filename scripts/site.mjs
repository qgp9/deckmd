#!/usr/bin/env node
// Builds the demo site (GitHub Pages) into _site/: the repository's launcher page, runtime and examples,
// with a generated deck.config.js — the intro deck as the home page, every example deck in the deck list (?deck-list).
// GitHub Pages has no directory listings, so decks: 'auto' can't scan there; the list is written here instead.
//   node scripts/site.mjs            → _site/   (run by .github/workflows/pages.yml)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, '_site');
const HOME = 'examples/intro/talk.md';

// title from the front matter, else the first # heading, else the path
const titleOf = (text, src) => {
  const fm = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] || '';
  const t = /^title:\s*(.+?)\s*$/m.exec(fm)?.[1]?.replace(/^(['"])(.*)\1$/, '$2');
  return t || /^#\s+(.+)$/m.exec(text)?.[1] || src;
};

// every example deck in git: examples/<deck>/*.md, the home deck first
const decks = execFileSync('git', ['ls-files', '-z', '--', 'examples/*/*.md'], { cwd: ROOT, encoding: 'utf8' }).split('\0').filter(Boolean).sort()
  .map(src => ({ src, title: titleOf(fs.readFileSync(path.join(ROOT, src), 'utf8'), src) }));
if (!decks.some(d => d.src === HOME)) throw new Error(`home deck not found: ${HOME}`);
decks.sort((a, b) => (b.src === HOME) - (a.src === HOME));

// copy what the site needs: the tracked files only (same result locally and in CI), not tests, tools, docs or local leftovers
fs.rmSync(OUT, { recursive: true, force: true });
const PARTS = ['index.html', 'LICENSE', 'js', 'css', 'themes', 'plugins', 'examples'];
const tracked = execFileSync('git', ['ls-files', '-z', '--', ...PARTS], { cwd: ROOT, encoding: 'utf8' }).split('\0').filter(Boolean);
for (const rel of tracked) {
  fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true });
  fs.copyFileSync(path.join(ROOT, rel), path.join(OUT, rel));
}

fs.writeFileSync(path.join(OUT, 'deck.config.js'), `// Generated by scripts/site.mjs for the demo site. The repository's own deck.config.js lists the examples by scanning instead.
window.DeckConfig = ${JSON.stringify({ title: 'deckmd examples', home: 'deck', src: HOME, decks }, null, 2)};
`);
// Safety net: deploying the artifact with GitHub Actions already skips Jekyll, but if the site is ever served
// from a branch instead, this keeps Jekyll from processing (and dropping) files.
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
console.log(`_site/: home ${HOME}, ${decks.length} decks in the list`);
